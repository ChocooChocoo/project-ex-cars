import { GCE_ROLES } from "../auth/roles";
import { isStaffRole, landingPath, resolveInternalPath, SUPPLIER_ROLE } from "./paths";

// Apache maps role-prefixed browser URLs to shared static files. The `gce-role` cookie is only a routing
// hint; Laravel authorises every request and SessionProvider checks the session in the browser.

/** Customer URL segments with their own route (see resolveInternalPath); anything else falls back like it. */
export const CUSTOMER_SEGMENTS = [
  "showroom",
  "inquiries",
  "my-inquiries",
  "my-transactions",
  "favourites",
  "recommendations",
  "sell-vehicle",
  "buying-requirements",
  "profile",
] as const;

// Apache regex escaping. Written with String.raw so no backslash is lost to string escaping or autofixes.
const BACKSLASH = String.raw`\ `.trim();
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\-]/g, (c) => BACKSLASH + c);
const COOKIE_SEP = String.raw`(^|;\s*)`;
const ROLE_COOKIE = `%{HTTP_COOKIE} ${COOKIE_SEP}gce-role=([a-z_]+)`;
const hasRole = (role: string) => `RewriteCond %{HTTP_COOKIE} ${COOKIE_SEP}gce-role=${role}(;|$)`;

// After an internal rewrite Apache runs these rules again on the new path. Redirects and the session check
// belong to the browser's own request only, so they are skipped on those later passes.
const FIRST_PASS = "RewriteCond %{ENV:REDIRECT_STATUS} ^$";

/**
 * @param dynamicBases export folders (relative to out/) that hold an `[id]` placeholder, e.g. ["showroom", "vehicles"].
 */
export function buildHtaccess(dynamicBases: readonly string[]): string {
  const lines: string[] = [
    "# Generated by src/scripts/generate-htaccess.ts. Do not edit; rebuild instead.",
    "Options -Indexes",
    "DirectoryIndex index.html",
    "ErrorDocument 404 /404.html",
    // Hostinger's CDN caches 404.html (static file, no Cache-Control) and serves it for the same URL to the next
    // visitor, skipping the gce-role redirect below. no-store keeps every 404 going through Apache.
    '<Files "404.html">',
    '  Header always set Cache-Control "no-store"',
    "</Files>",
    "RewriteEngine On",
    "",
    "# The client shares the landing link as /auth/v1; only login/ and register/ have pages.",
    "RewriteRule ^auth/v1/?$ /auth/v1/login/ [R=302,L]",
    "",
    "# Next 16 asks for page data as __next.<a>.<b>.txt but the export writes __next.<a>/<b>.txt; one dot per pass.",
    "# Before the auth/ exclusion below: auth pages have segment files too, and on Hostinger a 404 for one leaves",
    "# the browser's prefetch hanging.",
    "RewriteCond %{REQUEST_FILENAME} !-f",
    String.raw`RewriteRule ^(.*/)?(__next\.[^/.]+(?:/[^/.]+)*)\.([^/]+\.txt)$ $1$2/$3 [L]`,
    "",
    "# Files and pages that manage themselves.",
    "RewriteRule ^(_next|auth|template|unauthorized)(/|$) - [L]",
    "RewriteCond %{REQUEST_FILENAME} -f",
    "RewriteRule ^ - [L]",
    "",
    "# Pages end with a slash (trailingSlash: true).",
    FIRST_PASS,
    String.raw`RewriteCond %{REQUEST_URI} !\.[A-Za-z0-9]+$`,
    "RewriteRule ^(.*[^/])$ /$1/ [R=302,L]",
    "",
    "# Root: signed-in users go to their landing page; visitors see the public landing page.",
  ];
  for (const role of GCE_ROLES) {
    lines.push(FIRST_PASS, hasRole(role), `RewriteRule ^$ ${landingPath(role)}/ [R=302,L]`);
  }

  lines.push(
    "",
    "# /profile and the legacy /dashboard paths go to the role's own path.",
    FIRST_PASS,
    `RewriteCond ${ROLE_COOKIE}`,
    "RewriteRule ^profile/$ /%2/profile/ [R=302,L]",
  );
  for (const role of GCE_ROLES) {
    const target = isStaffRole(role) ? `/${role}/$1` : `${landingPath(role)}/`;
    lines.push(FIRST_PASS, hasRole(role), `RewriteRule ^dashboard/(.*)$ ${target} [R=302,L]`);
  }

  const roleAlternation = GCE_ROLES.map(esc).join("|");
  lines.push(
    "",
    "# Another role's prefix: swap in the signed-in role, keep the rest of the path.",
    FIRST_PASS,
    `RewriteCond ${ROLE_COOKIE}`,
    String.raw`RewriteCond %2::$1 !^([a-z_]+)::\1$`,
    `RewriteRule ^(${roleAlternation})/(.*)$ /%2/$2 [R=302,L]`,
    "",
    "# Signed out: every page but the public landing page needs a session.",
    FIRST_PASS,
    `RewriteCond %{HTTP_COOKIE} !${COOKIE_SEP}gce-role=`,
    "RewriteRule ^(.+)$ /auth/v1/login/ [R=302,L]",
  );

  lines.push("", "# Role-prefixed paths are served from the shared export folders.");
  for (const role of GCE_ROLES) {
    const r = esc(role);
    if (role === SUPPLIER_ROLE) {
      // The supplier portal is one export folder; anything else under /supplier/ lands on it.
      lines.push(`RewriteRule ^${r}/portal(/.*)?$ portal$1 [L]`, `RewriteRule ^${r}/ portal/ [L]`);
    } else if (isStaffRole(role)) {
      lines.push(`RewriteRule ^${r}/$ ${trim(resolveInternalPath(role, "dashboard"))}/ [L]`);
      lines.push(`RewriteRule ^${r}/dashboard/(.*)$ ${trim(resolveInternalPath(role, "dashboard"))}/$1 [L]`);
      lines.push(`RewriteRule ^${r}/recommendations(.*)$ ${trim(resolveInternalPath(role, "recommendations"))}$1 [L]`);
      lines.push(`RewriteRule ^${r}/(.*)$ $1 [L]`);
    } else {
      for (const segment of CUSTOMER_SEGMENTS) {
        const target = trim(resolveInternalPath(role, segment));
        lines.push(
          segment === "profile"
            ? `RewriteRule ^${r}/profile/$ ${target}/ [L]`
            : `RewriteRule ^${r}/${esc(segment)}(/.*)?$ ${target}$1 [L]`,
        );
      }
      lines.push(`RewriteRule ^${r}/ ${trim(resolveInternalPath(role, "unknown"))}/ [L]`);
    }
  }

  lines.push("", "# [id] pages are built once under the placeholder `_`; the page reads the id from the URL.");
  for (const base of dynamicBases) {
    lines.push("RewriteCond %{REQUEST_FILENAME} !-d", `RewriteRule ^${esc(base)}/(?!_/)[^/]+/(.*)$ ${base}/_/$1 [L]`);
  }
  return `${lines.join("\n")}\n`;
}

const trim = (path: string) => path.replace(/^\/+|\/+$/g, "");
